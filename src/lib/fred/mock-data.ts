export function getMockObservations(seriesId: string): FredObservationPoint[] {
  if (MOCK_SERIES_DATA[seriesId]) {
    return MOCK_SERIES_DATA[seriesId];
  }
  // Fallback procedural trend generator
  const points: FredObservationPoint[] = [];
  const now = new Date();
  let val = 100;
  for (let i = 18; i >= 0; i--) {
    const d = new Date(now.getFullYear(), now.getMonth() - i, 1);
    val = +(val + (Math.random() - 0.48) * 1.5).toFixed(2);
    points.push({
      date: d.toISOString().split("T")[0],
      value: val,
    });
  }
  return points;
}
